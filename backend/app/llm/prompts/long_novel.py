def ensure_stable_system_prefix(prompt: str, prefix: str) -> str:
    """Prepend a code-owned kernel to configurable legacy system prompts."""

    raw_prompt = prompt or ""
    if raw_prompt.startswith(prefix):
        return raw_prompt
    prompt = raw_prompt.strip()
    if not prompt:
        return prefix
    return f"{prefix}\n\n【兼容的可配置补充规则】\n{prompt}"
